package com.davils.kore.core.annotation

/**
 * Marks a class, function or property whose source was generated by a tool instead of written by hand.
 *
 * The builds of the Davils libraries leave declarations that carry it out of their coverage verification, because
 * their behaviour follows from the generator and its input; test the generator instead. The annotation is written to
 * the class files, where build tools find it, but is not visible through reflection at runtime.
 *
 * Both values are free text that is neither checked nor escaped. They ship inside the class files of the artifact, so
 * they must never hold a secret, such as a credential in the address of a schema.
 *
 * @property by the tool that generated the declaration, such as its name and version.
 * @property from the input the declaration was generated from, such as the path of a schema.
 * @since 1.0.0
 */
@Retention(AnnotationRetention.BINARY)
@Target(
    AnnotationTarget.CLASS,
    AnnotationTarget.FUNCTION,
    AnnotationTarget.PROPERTY,
)
@MustBeDocumented
public annotation class DavilsGenerated(
    val by: String,
    val from: String,
)
